#!/usr/bin/env bash
# Writes the overworld's programs (shaders/world0/, see shaders/dimension.properties) from the pack's own: every
# program file in shaders/ gets a copy there that defines WORLD_OVERWORLD before the rest. Iris loads a dimension's
# folder on its own, without falling back to the files above it, so every program has to be there. Run it after
# adding or removing a program in shaders/; the overworld's own programs (no "generated" line) are left alone.
#   shaderpack/world0.sh          write the copies
#   shaderpack/world0.sh --check  only say whether they are up to date (exit 1 if not)
set -euo pipefail
SHADERS="$(cd "$(dirname "$0")" && pwd)/shaders"
OUT="$SHADERS/world0"
MARK="// Generated by shaderpack/world0.sh from"
CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1
mkdir -p "$OUT"

stale=0
declare -A wanted=()
for src in "$SHADERS"/*.vsh "$SHADERS"/*.fsh "$SHADERS"/*.gsh "$SHADERS"/*.csh; do
    [[ -e "$src" ]] || continue
    name="$(basename "$src")"
    wanted["$name"]=1
    # The first line stays the #version line, as GLSL wants it.
    body="$(head -n 1 "$src")
$MARK $name
#define WORLD_OVERWORLD
$(tail -n +2 "$src")"
    dst="$OUT/$name"
    if [[ -e "$dst" ]] && ! grep -qF "$MARK" "$dst"; then
        echo "world0/$name is the overworld's own program, not overwriting it with shaders/$name" >&2
        stale=1
        continue
    fi
    if [[ ! -e "$dst" ]] || [[ "$(cat "$dst")" != "$body" ]]; then
        stale=1
        if (( CHECK )); then
            echo "world0/$name is out of date" >&2
        else
            printf '%s\n' "$body" > "$dst"
        fi
    fi
done

# Copies whose program is gone.
for dst in "$OUT"/*; do
    [[ -e "$dst" ]] || continue
    name="$(basename "$dst")"
    if grep -qF "$MARK" "$dst" && [[ -z "${wanted[$name]:-}" ]]; then
        stale=1
        if (( CHECK )); then
            echo "world0/$name has no program in shaders/ any more" >&2
        else
            rm "$dst"
        fi
    fi
done

if (( CHECK )); then
    (( stale )) && exit 1
    echo "world0 is up to date"
else
    echo "wrote $OUT"
fi
