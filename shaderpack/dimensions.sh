#!/usr/bin/env bash
# Writes the programs of the dimensions the pack draws its own way (see shaders/dimension.properties) from the
# pack's own: every program file in shaders/ gets a copy in the dimension's folder that defines the dimension's
# name before the rest (world0: WORLD_OVERWORLD, world1: WORLD_END). Iris loads a dimension's folder on its own,
# without falling back to the files above it, so every program has to be there. Run it after adding or removing a
# program in shaders/; a dimension's own programs (no "generated" line) are left alone.
#   shaderpack/dimensions.sh          write the copies
#   shaderpack/dimensions.sh --check  only say whether they are up to date (exit 1 if not)
set -euo pipefail
SHADERS="$(cd "$(dirname "$0")" && pwd)/shaders"
MARK="// Generated by shaderpack/dimensions.sh from"
DIMENSIONS=("world0:WORLD_OVERWORLD" "world1:WORLD_END")
CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

stale=0
for dimension in "${DIMENSIONS[@]}"; do
    folder="${dimension%%:*}"
    define="${dimension##*:}"
    out="$SHADERS/$folder"
    mkdir -p "$out"
    declare -A wanted=()
    for src in "$SHADERS"/*.vsh "$SHADERS"/*.fsh "$SHADERS"/*.gsh "$SHADERS"/*.csh; do
        [[ -e "$src" ]] || continue
        name="$(basename "$src")"
        wanted["$name"]=1
        # The first line stays the #version line, as GLSL wants it.
        body="$(head -n 1 "$src")
$MARK $name
#define $define
$(tail -n +2 "$src")"
        dst="$out/$name"
        if [[ -e "$dst" ]] && ! grep -qF "$MARK" "$dst"; then
            echo "$folder/$name is the dimension's own program, not overwriting it with shaders/$name" >&2
            stale=1
            continue
        fi
        if [[ ! -e "$dst" ]] || [[ "$(cat "$dst")" != "$body" ]]; then
            stale=1
            if (( CHECK )); then
                echo "$folder/$name is out of date" >&2
            else
                printf '%s\n' "$body" > "$dst"
            fi
        fi
    done

    # Copies whose program is gone.
    for dst in "$out"/*; do
        [[ -e "$dst" ]] || continue
        name="$(basename "$dst")"
        if grep -qF "$MARK" "$dst" && [[ -z "${wanted[$name]:-}" ]]; then
            stale=1
            if (( CHECK )); then
                echo "$folder/$name has no program in shaders/ any more" >&2
            else
                rm "$dst"
            fi
        fi
    done
    unset wanted
done

if (( CHECK )); then
    (( stale )) && exit 1
    echo "the dimensions' programs are up to date"
else
    echo "wrote ${DIMENSIONS[*]%%:*}"
fi
