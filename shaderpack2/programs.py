#!/usr/bin/env python3
"""Writes the pack's program files from program/: the files Iris looks for by name (gbuffers_terrain.fsh,
composite1.fsh, ...), each a few lines that set a version, the dimension and the program's own defines, then
include the program they use. The overworld and modded dimensions take shaders/ itself, the Nether world-1/ and
the End world1/ (Iris doesn't fall back from a dimension's folder to the files above it, so every program is in
each). Run it after adding or removing a program; --check only says whether the files are up to date.

    python3 shaderpack2/programs.py
    python3 shaderpack2/programs.py --check
"""

import sys
from pathlib import Path

SHADERS = Path(__file__).resolve().parent / "shaders"
MARK = "// Generated by shaderpack2/programs.py"
VERSION = "#version 430 compatibility"

# folder: (dimension define, whether it has the sky's tables)
FOLDERS = {
    "": (None, True),
    "world-1": ("WORLD_NETHER", False),
    "world1": ("WORLD_END", False),
}

# name: (stages {extension: program file}, defines, sky only)
PROGRAMS = {}


def add(name, stages, defines=(), sky_only=False):
    PROGRAMS[name] = (stages, list(defines), sky_only)


FULLSCREEN = "fullscreen.vsh"

# The air's tables: once when the pack loads, and the sky view each frame.
add("setup", {"csh": "sky.csh"}, ["SKY_TRANSMITTANCE"], sky_only=True)
add("setup1", {"csh": "sky.csh"}, ["SKY_MULTIPLE"], sky_only=True)
add("begin", {"csh": "sky.csh"}, ["SKY_VIEW"], sky_only=True)
# The light hash cleared, then the frame's light.
add("begin1", {"csh": "clear.csh"})
add("begin2", {"csh": "frame.csh"})

# The shadow pass: mobs and block entities, then the world's blocks (shadow map and voxel copy).
add("shadow", {"vsh": "shadow.vsh", "fsh": "shadow.fsh"})
for kind in ("solid", "cutout"):
    add("shadow_" + kind, {"vsh": "shadow.vsh", "gsh": "shadow.gsh", "fsh": "shadow.fsh"}, ["PROGRAM_SHADOW_TERRAIN"])
add("shadow_water", {"vsh": "shadow.vsh", "gsh": "shadow.gsh", "fsh": "shadow.fsh"},
    ["PROGRAM_SHADOW_TERRAIN", "PROGRAM_SHADOW_WATER"])
add("clrwl_shadow", {"vsh": "clrwl_shadow.vsh", "fsh": "clrwl_shadow.fsh"})

# The voxel copy's distance field, the light per block, the bounce light per block.
add("shadowcomp", {"csh": "barrier.csh"})
add("shadowcomp1", {"csh": "sdf.csh"})
add("shadowcomp2", {"csh": "voxel_light.csh"})
add("shadowcomp3", {"csh": "gi.csh"})

# The light per pixel and its filter, then the lighting.
add("deferred", {"csh": "pixel_light.csh"})
add("deferred1", {"csh": "pixel_light_filter.csh"})
add("deferred2", {"vsh": FULLSCREEN, "fsh": "deferred_light.fsh"})

# The air, the DLSS point, the bloom, the final pass.
add("composite", {"vsh": FULLSCREEN, "fsh": "fog.fsh"})
add("composite1", {"vsh": FULLSCREEN, "fsh": "dlss.fsh"})
for level in range(1, 7):
    add("composite%d" % (1 + level), {"csh": "bloom.csh"}, ["BLOOM_DOWN %d" % level])
for i, level in enumerate(range(5, 0, -1)):
    add("composite%d" % (8 + i), {"csh": "bloom.csh"}, ["BLOOM_UP %d" % level])
add("final", {"vsh": FULLSCREEN, "fsh": "final.fsh"})

# The world's programs.
WORLD = {"vsh": "gbuffers.vsh", "fsh": "gbuffers.fsh"}
for program in ("basic", "line", "textured", "textured_lit", "skybasic", "skytextured", "clouds", "terrain", "damagedblock",
                "block", "beaconbeam", "entities", "spidereyes", "armor_glint", "hand", "weather", "water",
                "hand_water", "particles", "lightning"):
    add("gbuffers_" + program, WORLD, ["PROGRAM_" + program.upper()])

# Create's machines through Colorwheel.
add("clrwl_gbuffers", WORLD, ["COLORWHEEL", "PROGRAM_CLRWL"])
for program in ("translucent", "glint", "additive", "lightning", "damagedblock"):
    add("clrwl_gbuffers_" + program, WORLD, ["COLORWHEEL", "PROGRAM_CLRWL_" + program.upper()])

# Distant Horizons.
for program in ("terrain", "water", "generic"):
    add("dh_" + program, {"vsh": "dh.vsh", "fsh": "dh.fsh"}, ["PROGRAM_DH_" + program.upper()])


def body(define, defines, source):
    lines = [VERSION, MARK]
    if define:
        lines.append("#define " + define)
    lines += ["#define " + d for d in defines]
    lines.append('#include "/program/%s"' % source)
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for folder, (define, has_sky) in FOLDERS.items():
        out = SHADERS / folder if folder else SHADERS
        wanted = {}
        for name, (stages, defines, sky_only) in PROGRAMS.items():
            if sky_only and not has_sky:
                continue
            for ext, source in stages.items():
                if not (SHADERS / "program" / source).is_file():
                    sys.exit("program/%s (for %s.%s) doesn't exist" % (source, name, ext))
                wanted["%s.%s" % (name, ext)] = body(define, defines, source)
        if not check:
            out.mkdir(parents=True, exist_ok=True)
        for file, text in wanted.items():
            path = out / file
            if path.is_file() and MARK not in path.read_text():
                sys.exit("%s isn't one of this script's files, not overwriting it" % path.relative_to(SHADERS))
            if not path.is_file() or path.read_text() != text:
                stale.append(path)
                if not check:
                    path.write_text(text)
        # Files of programs that are gone.
        if out.is_dir():
            for path in out.iterdir():
                if path.suffix in (".vsh", ".gsh", ".fsh", ".csh") and path.name not in wanted \
                        and MARK in path.read_text():
                    stale.append(path)
                    if not check:
                        path.unlink()
    if check:
        for path in stale:
            print("%s is out of date" % path.relative_to(SHADERS), file=sys.stderr)
        sys.exit(1 if stale else 0)
    print("wrote %d files" % len(stale) if stale else "the programs are up to date")


if __name__ == "__main__":
    main()
